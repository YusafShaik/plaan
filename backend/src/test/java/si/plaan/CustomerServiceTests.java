package si.plaan;

import org.junit.jupiter.api.Assertions;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.data.domain.PageRequest;
import org.springframework.transaction.annotation.Transactional;
import si.plaan.dto.request.CreateCustomerRequest;
import si.plaan.dto.request.UpdateCustomerRequest;
import si.plaan.dto.response.CustomerResponse;
import si.plaan.dto.response.CustomerSummaryResponse;
import si.plaan.dto.response.PageResponse;
import si.plaan.entity.Organization;
import si.plaan.repository.OrganizationRepository;
import si.plaan.service.CustomerService;

import java.util.UUID;

@SpringBootTest
@Transactional
public class CustomerServiceTests {

    @Autowired
    private CustomerService customerService;

    @Autowired
    private OrganizationRepository organizationRepository;

    private Organization orgA;
    private Organization orgB;

    @BeforeEach
    void setUp() {
        orgA = organizationRepository.save(Organization.builder()
                .name("Tenant Org A")
                .slug("org-a-" + UUID.randomUUID().toString().substring(0, 8))
                .country("India")
                .baseCurrency("INR")
                .timeZone("Asia/Kolkata")
                .active(true)
                .build());

        orgB = organizationRepository.save(Organization.builder()
                .name("Tenant Org B")
                .slug("org-b-" + UUID.randomUUID().toString().substring(0, 8))
                .country("USA")
                .baseCurrency("USD")
                .timeZone("UTC")
                .active(true)
                .build());
    }

    @Test
    void testCreateCustomerWithAutoGeneratedCode() {
        String nextCode = customerService.getNextCustomerCode(orgA.getId());
        Assertions.assertTrue(nextCode.startsWith("CUS-"));

        CreateCustomerRequest request = new CreateCustomerRequest(
                null,
                "ABC Furniture",
                "Ravi Kumar",
                "+91 9876543210",
                "ravi@abcfurniture.com",
                "Plot 12, Industrial Area, Bangalore",
                "Plot 45, Logistics Park, Bangalore",
                "29ABCDE1234F1Z5",
                true
        );

        CustomerResponse response = customerService.createCustomer(orgA.getId(), request);
        Assertions.assertNotNull(response.id());
        Assertions.assertEquals(nextCode, response.customerCode());
        Assertions.assertEquals("ABC Furniture", response.name());
        Assertions.assertEquals("Ravi Kumar", response.contactPerson());
        Assertions.assertEquals("Plot 12, Industrial Area, Bangalore", response.billingAddress());
        Assertions.assertEquals("Plot 45, Logistics Park, Bangalore", response.shippingAddress());
        Assertions.assertTrue(response.active());
    }

    @Test
    void testCreateCustomerWithCustomCode() {
        CreateCustomerRequest request = new CreateCustomerRequest(
                "CUS-999",
                "Modern Interiors",
                "Suresh Rao",
                "+91 9123456789",
                "suresh@moderninteriors.com",
                "45 Commercial Street, Mumbai",
                "45 Commercial Street, Mumbai",
                "27ABCDE5678G1Z2",
                true
        );

        CustomerResponse response = customerService.createCustomer(orgA.getId(), request);
        Assertions.assertEquals("CUS-999", response.customerCode());
        Assertions.assertEquals("Modern Interiors", response.name());
    }

    @Test
    void testPreventDuplicateCustomerCodeInSameOrganization() {
        CreateCustomerRequest req1 = new CreateCustomerRequest(
                "CUS-001",
                "ABC Furniture",
                null, null, null, null, null, null, true
        );
        customerService.createCustomer(orgA.getId(), req1);

        CreateCustomerRequest req2 = new CreateCustomerRequest(
                "cus-001", // case-insensitive duplicate
                "Duplicate Code Co",
                null, null, null, null, null, null, true
        );

        IllegalArgumentException ex = Assertions.assertThrows(
                IllegalArgumentException.class,
                () -> customerService.createCustomer(orgA.getId(), req2)
        );
        Assertions.assertTrue(ex.getMessage().contains("already registered in this organization"));
    }

    @Test
    void testTenantDataIsolation() {
        // Org A creates CUS-100
        CustomerResponse resA = customerService.createCustomer(orgA.getId(), new CreateCustomerRequest(
                "CUS-100", "Tenant A Customer", null, null, null, null, null, null, true
        ));

        // Org B can create identical CUS-100 without constraint violation
        CustomerResponse resB = customerService.createCustomer(orgB.getId(), new CreateCustomerRequest(
                "CUS-100", "Tenant B Customer", null, null, null, null, null, null, true
        ));

        Assertions.assertNotNull(resA.id());
        Assertions.assertNotNull(resB.id());
        Assertions.assertNotEquals(resA.id(), resB.id());

        // Org A cannot access Org B's customer
        Assertions.assertThrows(Exception.class, () ->
                customerService.getCustomerById(orgA.getId(), resB.id()));

        // Org B cannot access Org A's customer
        Assertions.assertThrows(Exception.class, () ->
                customerService.getCustomerById(orgB.getId(), resA.id()));

        // Querying customers for Org A returns only Org A's customer
        PageResponse<CustomerResponse> pageA = customerService.getCustomers(
                orgA.getId(), null, null, PageRequest.of(0, 10));
        Assertions.assertEquals(1, pageA.totalElements());
        Assertions.assertEquals("Tenant A Customer", pageA.content().get(0).name());
    }

    @Test
    void testInvalidEmailFormatValidation() {
        CreateCustomerRequest invalidReq = new CreateCustomerRequest(
                null,
                "Bad Email Corp",
                null,
                null,
                "not-an-email",
                null,
                null,
                null,
                true
        );

        IllegalArgumentException ex = Assertions.assertThrows(
                IllegalArgumentException.class,
                () -> customerService.createCustomer(orgA.getId(), invalidReq)
        );
        Assertions.assertTrue(ex.getMessage().contains("Invalid email format"));
    }

    @Test
    void testUpdateCustomerAndToggleStatus() {
        CustomerResponse created = customerService.createCustomer(orgA.getId(), new CreateCustomerRequest(
                null, "Initial Name", "Old Contact", null, null, null, null, null, true
        ));

        UpdateCustomerRequest updateReq = new UpdateCustomerRequest(
                "Updated Name",
                "New Contact",
                "+91 9999988888",
                "new@contact.com",
                "New Billing Address",
                "New Shipping Address",
                "29TAXID123",
                false
        );

        CustomerResponse updated = customerService.updateCustomer(orgA.getId(), created.id(), updateReq);
        Assertions.assertEquals("Updated Name", updated.name());
        Assertions.assertEquals("New Contact", updated.contactPerson());
        Assertions.assertEquals("+91 9999988888", updated.phone());
        Assertions.assertEquals("new@contact.com", updated.email());
        Assertions.assertEquals("New Billing Address", updated.billingAddress());
        Assertions.assertEquals("New Shipping Address", updated.shippingAddress());
        Assertions.assertFalse(updated.active());

        // Toggle status
        CustomerResponse toggled = customerService.toggleStatus(orgA.getId(), created.id());
        Assertions.assertTrue(toggled.active());
    }

    @Test
    void testSearchAndSummary() {
        customerService.createCustomer(orgA.getId(), new CreateCustomerRequest(
                "CUS-001", "ABC Furniture", "Ravi Kumar", null, null, null, null, null, true
        ));
        customerService.createCustomer(orgA.getId(), new CreateCustomerRequest(
                "CUS-002", "Modern Interiors", "Suresh Rao", null, null, null, null, null, true
        ));
        customerService.createCustomer(orgA.getId(), new CreateCustomerRequest(
                "CUS-003", "City Furnishings", "Anil Reddy", null, null, null, null, null, false
        ));

        CustomerSummaryResponse summary = customerService.getSummary(orgA.getId());
        Assertions.assertEquals(3, summary.totalCustomers());
        Assertions.assertEquals(2, summary.activeCustomers());
        Assertions.assertEquals(1, summary.inactiveCustomers());

        // Search by code
        PageResponse<CustomerResponse> searchByCode = customerService.getCustomers(
                orgA.getId(), "CUS-001", null, PageRequest.of(0, 10));
        Assertions.assertEquals(1, searchByCode.totalElements());
        Assertions.assertEquals("ABC Furniture", searchByCode.content().get(0).name());

        // Search by name
        PageResponse<CustomerResponse> searchByName = customerService.getCustomers(
                orgA.getId(), "Interiors", null, PageRequest.of(0, 10));
        Assertions.assertEquals(1, searchByName.totalElements());
        Assertions.assertEquals("Modern Interiors", searchByName.content().get(0).name());

        // Filter by active
        PageResponse<CustomerResponse> activeOnly = customerService.getCustomers(
                orgA.getId(), null, true, PageRequest.of(0, 10));
        Assertions.assertEquals(2, activeOnly.totalElements());

        // Filter by inactive
        PageResponse<CustomerResponse> inactiveOnly = customerService.getCustomers(
                orgA.getId(), null, false, PageRequest.of(0, 10));
        Assertions.assertEquals(1, inactiveOnly.totalElements());
        Assertions.assertEquals("City Furnishings", inactiveOnly.content().get(0).name());
    }

    @Test
    void testDeleteCustomer() {
        CustomerResponse created = customerService.createCustomer(orgA.getId(), new CreateCustomerRequest(
                null, "To Be Deleted", null, null, null, null, null, null, true
        ));

        customerService.deleteCustomer(orgA.getId(), created.id());

        Assertions.assertThrows(Exception.class, () ->
                customerService.getCustomerById(orgA.getId(), created.id()));
    }
}
